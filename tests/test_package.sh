#!/bin/sh
set -eu
ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
SRC="$ROOT/src/aurora.c"
test -s "$SRC"
grep -q '#include <SDL.h>' "$SRC"
grep -q 'SDL_CreateWindow' "$SRC"
grep -q 'ffprobe' "$SRC"
grep -q 'input-ipc-server' "$SRC"
grep -q 'APP_VERSION "0.4.1"' "$SRC"
grep -q 'SDL_CONTROLLERBUTTONDOWN' "$SRC"
grep -q 'SDL_CONTROLLER_BUTTON_DPAD_LEFT' "$SRC"
grep -q 'button==8' "$SRC"
grep -q 'if(button==9)' "$SRC"
grep -q 'if(button==0)' "$SRC"
grep -q 'controller_button(SDL_CONTROLLER_BUTTON_B,1)' "$SRC"
grep -q 'controller_button(SDL_CONTROLLER_BUTTON_A,1)' "$SRC"
grep -q 'Select=8 and Start=9' "$ROOT/README.md"
grep -q 'LED Wave selects the controller' "$ROOT/README.md"
grep -q 'volume_overlay_until' "$SRC"
grep -q 'render_status_bar' "$SRC"
grep -q 'render_volume_overlay' "$SRC"
grep -q 'LIST_RECENT' "$SRC"
grep -q 'LED WAVE' "$SRC"
grep -q 'SDL_LoadBMP(path)' "$SRC"
grep -q 'theme=%d' "$SRC"
grep -q 'artwork_dir' "$SRC"
test -f "$ROOT/icons/songs.bmp"
grep -q '/sys/class/leds/joyled/brightness' "$SRC"
grep -q 'batocera-led-handheld' "$SRC"
grep -q 'CHECK FOR UPDATES' "$SRC"
if grep -q 'PAGE_BUTTON_SETUP\|BUTTON MAPPING COMPLETE\|button_setup_done' "$SRC"; then
  echo "Obsolete controller remapping wizard found in v0.4.1 source." >&2
  exit 1
fi
grep -q 'aps456/Aurora-R36' "$ROOT/github_repo.txt"
grep -q 'Aurora_R36_aarch64.zip' "$ROOT/update.sh"
grep -q 'Aurora_R36_armv7.zip' "$ROOT/update.sh"
grep -q 'Version: 0.4.1' "$ROOT/package-release.sh"
grep -q 'ports/Aurora-R36/aurora' "$ROOT/package-release.sh"
grep -q 'docker/setup-qemu-action' "$ROOT/.github/workflows/release.yml"
grep -q 'default: '\''v0.4.1'\''' "$ROOT/.github/workflows/release.yml"
grep -q 'softprops/action-gh-release@v3' "$ROOT/.github/workflows/release.yml"
for f in "$ROOT"/*.sh "$ROOT"/tests/*.sh; do
  test -f "$f"
  sh -n "$f"
  test -x "$f"
done
test -f "$ROOT/Makefile"
test -f "$ROOT/.github/workflows/release.yml"
echo "Aurora v0.4.1 source and packaging checks passed."
